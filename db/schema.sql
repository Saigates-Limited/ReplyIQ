-- ReplyIQ schema (PostgreSQL)

-- ───────────── Staff authentication ─────────────
CREATE TABLE IF NOT EXISTS users (
  id            SERIAL PRIMARY KEY,
  email         TEXT UNIQUE NOT NULL,
  name          TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('agent','manager')),
  password_hash TEXT NOT NULL,          -- pbkdf2$<iterations>$<salt_b64>$<hash_b64>
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_login_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS sessions (
  id          TEXT PRIMARY KEY,         -- sha256 of the cookie token
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at  TIMESTAMPTZ NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

-- ───────────── Cases ─────────────
CREATE TABLE IF NOT EXISTS cases (
  id                    SERIAL PRIMARY KEY,
  case_ref              TEXT UNIQUE NOT NULL,          -- e.g. RIQ-1042
  subject               TEXT NOT NULL,
  status                TEXT NOT NULL DEFAULT 'open',  -- open | awaiting_customer | resolved

  -- Customer identity. ONLY first_name may ever be sent to OpenAI.
  customer_first_name   TEXT NOT NULL,
  customer_last_name    TEXT,                          -- PII: never leaves the server
  customer_email        TEXT,                          -- PII: never leaves the server
  customer_phone        TEXT,                          -- PII: never leaves the server
  customer_address      TEXT,                          -- PII: never leaves the server

  -- Agent-filled fields
  order_id              TEXT,
  device_model          TEXT,
  delivery_date         DATE,
  refund_issued         BOOLEAN,
  a_to_z_open           BOOLEAN,
  in_stock              BOOLEAN,
  approved_repair_price NUMERIC(10,2),
  repair_quote_accepted BOOLEAN,                       -- customer accepted the approved paid-repair quote
  tracking_number       TEXT,
  carrier               TEXT,

  -- Gmail source (NULL for manually created cases)
  gmail_thread_id       TEXT,                           -- latest thread for this case (Amazon opens one thread per message)
  customer_reply_to     TEXT,                          -- anonymised @marketplace.amazon.co.uk address; server only
  source                TEXT NOT NULL DEFAULT 'manual', -- manual | gmail | amazon_notice

  -- Ticket fields
  assigned_to           INTEGER REFERENCES users(id) ON DELETE SET NULL,
  internal_notes        TEXT,                          -- never sent to customer or OpenAI
  tone                  TEXT CHECK (tone IN ('angry','dispute','frustrated','worried','neutral','happy')),
  chargeback_open       BOOLEAN NOT NULL DEFAULT FALSE,
  battery_flag          BOOLEAN NOT NULL DEFAULT FALSE,

  -- reply_deadline is derived in queries as last_customer_message_at + 24h
  last_customer_message_at TIMESTAMPTZ NOT NULL,

  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS messages (
  id          SERIAL PRIMARY KEY,
  case_id     INTEGER NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  direction   TEXT NOT NULL CHECK (direction IN ('inbound','outbound')),
  sender      TEXT NOT NULL,     -- display label, e.g. "Customer" or "Saigates Support"
  body        TEXT NOT NULL,
  subject     TEXT,
  gmail_message_id TEXT UNIQUE,
  rfc_message_id   TEXT,          -- Message-ID header, for In-Reply-To / References
  tone        TEXT CHECK (tone IN ('angry','dispute','frustrated','worried','neutral','happy')),
  tone_source TEXT,               -- ai | staff
  tone_model  TEXT,
  kind        TEXT NOT NULL DEFAULT 'message', -- message | seller_central_copy | event
  event_id    INTEGER,            -- FK to amazon_events added below
  sent_at     TIMESTAMPTZ NOT NULL DEFAULT now()  -- Gmail internalDate for ingested mail
);

-- Drafts generated by the AI, edited/approved by agents. Nothing is auto-sent.
CREATE TABLE IF NOT EXISTS drafts (
  id              SERIAL PRIMARY KEY,
  case_id         INTEGER NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  tree            TEXT,                                 -- decision tree the model selected
  draft_text      TEXT NOT NULL,                        -- current (possibly edited) text
  original_text   TEXT NOT NULL,                        -- as returned by the model
  staff_notes     TEXT,
  check_result    TEXT CHECK (check_result IN ('PASS','FAIL')),
  check_findings  JSONB,                                -- model guardrail findings
  server_findings JSONB,                                -- deterministic server-side checks
  needs_manager   BOOLEAN NOT NULL DEFAULT FALSE,
  needs_manager_reason TEXT,
  urgency         TEXT CHECK (urgency IN ('high','normal','low')),
  model           TEXT,
  status          TEXT NOT NULL DEFAULT 'draft',        -- draft | approved | sent | discarded
  created_by      INTEGER REFERENCES users(id) ON DELETE SET NULL,
  edited_by       INTEGER REFERENCES users(id) ON DELETE SET NULL,
  edited_at       TIMESTAMPTZ,
  approved_by     INTEGER REFERENCES users(id) ON DELETE SET NULL,
  approved_at     TIMESTAMPTZ,
  sent_recorded_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  sent_recorded_at TIMESTAMPTZ,
  sent_via        TEXT,                                 -- gmail | manual
  sent_gmail_message_id TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_cases_deadline ON cases(last_customer_message_at);
CREATE INDEX IF NOT EXISTS idx_messages_case ON messages(case_id, sent_at);
CREATE INDEX IF NOT EXISTS idx_drafts_case ON drafts(case_id, created_at DESC);

-- ───────────── Gmail integration ─────────────
CREATE TABLE IF NOT EXISTS gmail_connection (
  id                  INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  email_address       TEXT NOT NULL,
  refresh_token_enc   TEXT NOT NULL,          -- AES-GCM, base64(iv || ciphertext), key = TOKEN_ENC_KEY secret
  scopes              TEXT NOT NULL,
  connected_by        INTEGER REFERENCES users(id) ON DELETE SET NULL,
  connected_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_sync_at        TIMESTAMPTZ,
  last_sync_status    TEXT,
  last_sync_error     TEXT,
  last_sync_new_msgs  INTEGER
);

CREATE TABLE IF NOT EXISTS oauth_states (
  state       TEXT PRIMARY KEY,
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sync_runs (
  id            SERIAL PRIMARY KEY,
  started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at   TIMESTAMPTZ,
  trigger       TEXT NOT NULL,                -- cron | manual
  threads_seen  INTEGER DEFAULT 0,
  messages_new  INTEGER DEFAULT 0,
  cases_new     INTEGER DEFAULT 0,
  status        TEXT,
  error         TEXT
);
CREATE INDEX IF NOT EXISTS idx_sync_runs_started ON sync_runs(started_at DESC);
CREATE SEQUENCE IF NOT EXISTS case_ref_seq;
CREATE TABLE IF NOT EXISTS gmail_threads_seen (thread_id TEXT PRIMARY KEY, history_id TEXT, seen_at TIMESTAMPTZ NOT NULL DEFAULT now());

-- ───────── Amazon notices ─────────
CREATE TABLE IF NOT EXISTS amazon_events (
  id                SERIAL PRIMARY KEY,
  case_id           INTEGER REFERENCES cases(id) ON DELETE CASCADE,
  order_id          TEXT NOT NULL,
  kind              TEXT NOT NULL CHECK (kind IN ('atoz_claim','atoz_info_request','atoz_decision','return_request','chargeback')),
  status            TEXT NOT NULL DEFAULT 'open',    -- atoz/chargeback: open | response_sent | won | lost ; return: requested | received | inspected | refunded | closed
  amount            NUMERIC(10,2),
  currency          TEXT DEFAULT 'GBP',
  received_at       TIMESTAMPTZ NOT NULL,            -- Gmail internalDate of the notice
  deadline_at       TIMESTAMPTZ,                     -- chargeback: +7d ; atoz_info_request: +3d ; otherwise NULL
  -- return-specific
  return_request_date DATE,
  policy_check      TEXT,
  authorisation     TEXT,
  asin              TEXT,
  sku               TEXT,
  quantity          INTEGER,
  return_reason     TEXT,
  customer_comment  TEXT,
  -- chargeback-specific
  order_date        TIMESTAMPTZ,
  item_description  TEXT,
  reply_to          TEXT,                            -- Reply-To header of the notice (checked before any send is enabled)
  -- generic
  product           TEXT,
  gmail_message_id  TEXT UNIQUE,
  gmail_thread_id   TEXT,
  raw_excerpt       TEXT,                            -- redacted excerpt for the timeline
  response_text     TEXT,                            -- what staff pasted into Seller Central / emailed
  responded_by      INTEGER REFERENCES users(id) ON DELETE SET NULL,
  responded_at      TIMESTAMPTZ,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_events_case ON amazon_events(case_id);
CREATE INDEX IF NOT EXISTS idx_events_kind_status ON amazon_events(kind, status);
CREATE INDEX IF NOT EXISTS idx_events_deadline ON amazon_events(deadline_at);

ALTER TABLE messages ADD COLUMN IF NOT EXISTS event_id INTEGER REFERENCES amazon_events(id) ON DELETE CASCADE;
