-- ReplyIQ schema (PostgreSQL)

CREATE TABLE IF NOT EXISTS cases (
  id                    SERIAL PRIMARY KEY,
  case_ref              TEXT UNIQUE NOT NULL,          -- e.g. RIQ-1042
  subject               TEXT NOT NULL,
  status                TEXT NOT NULL DEFAULT 'open',  -- open | awaiting_customer | resolved

  -- Customer identity. ONLY first_name may ever be sent to OpenAI.
  customer_first_name   TEXT NOT NULL,
  customer_last_name    TEXT,                          -- PII: never leaves the server
  customer_email        TEXT,                          -- PII: never leaves the server
  customer_phone        TEXT,                          -- PII: never leaves the server
  customer_address      TEXT,                          -- PII: never leaves the server

  -- Agent-filled fields
  order_id              TEXT,
  device_model          TEXT,
  delivery_date         DATE,
  refund_issued         BOOLEAN,
  a_to_z_open           BOOLEAN,
  in_stock              BOOLEAN,
  approved_repair_price NUMERIC(10,2),
  tracking_number       TEXT,
  carrier               TEXT,

  -- Deadline = 24h after latest inbound customer message
  -- reply_deadline is derived in queries as last_customer_message_at + 24h
  last_customer_message_at TIMESTAMPTZ NOT NULL,

  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS messages (
  id          SERIAL PRIMARY KEY,
  case_id     INTEGER NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  direction   TEXT NOT NULL CHECK (direction IN ('inbound','outbound')),
  sender      TEXT NOT NULL,     -- display label, e.g. "Customer" or "Saigates Support"
  body        TEXT NOT NULL,
  sent_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Drafts generated by the AI, edited/approved by agents. Nothing is auto-sent.
CREATE TABLE IF NOT EXISTS drafts (
  id            SERIAL PRIMARY KEY,
  case_id       INTEGER NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  draft_text    TEXT NOT NULL,
  staff_notes   TEXT,
  check_result  TEXT CHECK (check_result IN ('PASS','FAIL')),
  check_details TEXT,
  model         TEXT,
  status        TEXT NOT NULL DEFAULT 'draft',  -- draft | approved
  approved_by   TEXT,
  approved_at   TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_cases_deadline ON cases(last_customer_message_at);
CREATE INDEX IF NOT EXISTS idx_messages_case ON messages(case_id, sent_at);
CREATE INDEX IF NOT EXISTS idx_drafts_case ON drafts(case_id, created_at DESC);
